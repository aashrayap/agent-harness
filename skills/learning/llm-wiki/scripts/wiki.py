#!/usr/bin/env python3
import argparse
import datetime
import json
import re
import shutil
import sys
from pathlib import Path

SKILL = Path(__file__).resolve().parents[1]
PAGE_DIRS = ("sources", "topics", "entities")
TYPES = {"sources": "source", "topics": "topic", "entities": "entity"}
REQUIRED = ("title", "type", "summary", "updated", "confidence", "status")
CONFIDENCE = {"measured", "inferred", "guess"}
STATUS = {"current", "stale", "superseded"}
LINK = re.compile(r"\[\[([^\]|#]+)(?:[#|][^\]]*)?\]\]")
INDEX_HEADINGS = {"topic": "Topics", "entity": "Entities", "source": "Sources"}


def parse_frontmatter(text):
    if not text.startswith("---\n"):
        return None
    end = text.find("\n---", 4)
    if end == -1:
        return None
    meta = {}
    key = None
    for line in text[4:end].splitlines():
        if line.startswith((" ", "\t")):
            if key and line.strip().startswith("- ") and not meta.get(key):
                meta[key] = "block list"
            continue
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        key = key.strip()
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            meta[key] = [v.strip() for v in value[1:-1].split(",") if v.strip()]
        else:
            meta[key] = value.strip("\"'")
    return meta


def load_pages(root, duplicates=None):
    pages = {}
    for folder in PAGE_DIRS:
        for path in sorted((root / folder).glob("*.md")):
            text = path.read_text(encoding="utf-8")
            if path.stem in pages and duplicates is not None:
                duplicates.append(f"{folder}/{path.name} and {pages[path.stem]['folder']}/{path.name}")
            pages[path.stem] = {"path": path, "folder": folder, "meta": parse_frontmatter(text), "text": text}
    return pages


def render_index(root):
    pages = load_pages(root)
    lines = [
        "# Index",
        "",
        "Generated by `wiki.py index` from each page's frontmatter; do not edit by hand.",
        "Read this first, then open only the pages that match the question.",
    ]
    for kind in ("topic", "entity", "source"):
        rows = [(slug, p) for slug, p in pages.items() if p["meta"] and p["meta"].get("type") == kind]
        if not rows:
            continue
        lines += ["", f"## {INDEX_HEADINGS[kind]}", ""]
        for slug, page in sorted(rows):
            meta = page["meta"]
            flag = "" if meta.get("status") == "current" else f" ({meta.get('status')})"
            lines.append(f"- [[{slug}]] {meta.get('summary', '')}{flag}")
    return "\n".join(lines) + "\n"


def build_index(root):
    text = render_index(root)
    (root / "index.md").write_text(text, encoding="utf-8")
    return text


def lint(root, today, stale_days):
    duplicates = []
    pages = load_pages(root, duplicates)
    findings = [{"kind": "duplicate-slug", "page": d, "detail": ""} for d in duplicates]
    inbound = {slug: 0 for slug in pages}
    index_text = (root / "index.md").read_text(encoding="utf-8") if (root / "index.md").exists() else ""
    indexed = set(LINK.findall(index_text))
    for slug, page in pages.items():
        rel = f"{page['folder']}/{slug}.md"
        meta = page["meta"]
        if meta is None:
            findings.append({"kind": "no-frontmatter", "page": rel, "detail": ""})
            continue
        listed = sorted(k for k, v in meta.items() if k != "sources" and isinstance(v, list))
        if listed:
            findings.append({"kind": "list-field", "page": rel, "detail": ", ".join(listed)})
            meta = {k: ", ".join(v) if k in listed else v for k, v in meta.items()}
        missing = [k for k in REQUIRED if not meta.get(k)]
        if missing:
            findings.append({"kind": "missing-field", "page": rel, "detail": ", ".join(missing)})
        if meta.get("type") and meta["type"] != TYPES[page["folder"]]:
            findings.append({"kind": "wrong-type", "page": rel, "detail": meta["type"]})
        if meta.get("confidence") and meta["confidence"] not in CONFIDENCE:
            findings.append({"kind": "bad-confidence", "page": rel, "detail": meta["confidence"]})
        if meta.get("status") and meta["status"] not in STATUS:
            findings.append({"kind": "bad-status", "page": rel, "detail": meta["status"]})
        if meta.get("status") == "superseded" and meta.get("superseded_by") not in pages:
            findings.append({"kind": "superseded-without-target", "page": rel, "detail": meta.get("superseded_by", "")})
        if meta.get("sources") and not isinstance(meta["sources"], list):
            findings.append({"kind": "bad-sources", "page": rel, "detail": "write sources as [a, b]"})
        for source in meta.get("sources", []) if isinstance(meta.get("sources"), list) else []:
            if source not in pages:
                findings.append({"kind": "unknown-source", "page": rel, "detail": source})
            elif source != slug:
                inbound[source] += 1
        try:
            age = (today - datetime.date.fromisoformat(meta.get("updated", ""))).days
        except ValueError:
            age = None
            if meta.get("updated"):
                findings.append({"kind": "bad-date", "page": rel, "detail": meta["updated"]})
        if age is not None and age > stale_days and meta.get("status") == "current" and meta.get("type") != "source":
            findings.append({"kind": "stale", "page": rel, "detail": f"{age} days"})
        if slug not in indexed:
            findings.append({"kind": "not-in-index", "page": rel, "detail": ""})
        for target in set(LINK.findall(page["text"])):
            target = target.strip()
            if target in inbound and target != slug:
                inbound[target] += 1
            elif target not in pages:
                findings.append({"kind": "broken-link", "page": rel, "detail": target})
    for slug in sorted(indexed - set(pages)):
        findings.append({"kind": "index-out-of-date", "page": "index.md", "detail": slug})
    if index_text != render_index(root) and not any(
            f["kind"] in {"index-out-of-date", "not-in-index"} for f in findings):
        findings.append({"kind": "index-out-of-date", "page": "index.md", "detail": "run wiki.py index"})
    for slug, count in inbound.items():
        if count == 0 and pages[slug]["meta"] and pages[slug]["meta"].get("type") != "topic":
            findings.append({"kind": "orphan", "page": f"{pages[slug]['folder']}/{slug}.md", "detail": ""})
    inbox = root.parent / "inbox" if (root.parent / "inbox").exists() else root / "inbox"
    waiting = sorted(p.name for p in inbox.iterdir() if p.is_dir()) if inbox.exists() else []
    for name in waiting:
        findings.append({"kind": "inbox-waiting", "page": f"inbox/{name}", "detail": ""})
    return {"pages": len(pages), "findings": findings}


def init(root, inbox):
    created = []
    for folder in ("raw", *PAGE_DIRS):
        (root / folder).mkdir(parents=True, exist_ok=True)
    inbox.mkdir(parents=True, exist_ok=True)
    schema = root / "AGENTS.md"
    if not schema.exists():
        shutil.copyfile(SKILL / "references" / "schema.md", schema)
        created.append(str(schema))
    log = root / "log.md"
    if not log.exists():
        log.write_text("# Log\n\nAppend-only. One line per page touched: `YYYY-MM-DD op slug: what changed`.\n", encoding="utf-8")
        created.append(str(log))
    if not (root / "index.md").exists():
        build_index(root)
        created.append(str(root / "index.md"))
    return created


def main(argv=None):
    parser = argparse.ArgumentParser(prog="wiki.py")
    sub = parser.add_subparsers(dest="cmd", required=True)
    p_init = sub.add_parser("init")
    p_init.add_argument("root", type=Path)
    p_init.add_argument("--inbox", type=Path)
    p_index = sub.add_parser("index")
    p_index.add_argument("root", type=Path)
    p_lint = sub.add_parser("lint")
    p_lint.add_argument("root", type=Path)
    p_lint.add_argument("--json", action="store_true")
    p_lint.add_argument("--stale-days", type=int, default=30)
    p_lint.add_argument("--today", type=datetime.date.fromisoformat, default=datetime.date.today())
    args = parser.parse_args(argv)
    if args.cmd == "init":
        for path in init(args.root, args.inbox or args.root.parent / "inbox"):
            print(f"created {path}")
        return 0
    if args.cmd == "index":
        build_index(args.root)
        print(f"wrote {args.root / 'index.md'}")
        return 0
    if not (args.root / "index.md").exists():
        print(f"{args.root} has no index.md; run init or index first", file=sys.stderr)
        return 2
    report = lint(args.root, args.today, args.stale_days)
    if args.json:
        print(json.dumps(report, indent=2))
    else:
        for f in report["findings"]:
            print(f"{f['kind']}\t{f['page']}\t{f['detail']}".rstrip())
        print(f"{report['pages']} pages, {len(report['findings'])} findings")
    blocking = [f for f in report["findings"] if f["kind"] not in {"stale", "orphan", "inbox-waiting"}]
    return 1 if blocking else 0


if __name__ == "__main__":
    sys.exit(main())
