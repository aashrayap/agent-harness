#!/usr/bin/env python3
import hashlib
import json
import re
import sys
from pathlib import Path

from conform import RULES, checks, hand_edited

ROOT = Path(__file__).resolve().parents[1]
ADOPTED = re.compile(r"follows template (\d+)", re.I)
KEEP = ("Always pause", "Models", "Every repo", "Judgment", "Communication")
MAC_ONLY = re.compile(r"~/|\bpos\b|show_widget|\bsetup\b|verify-profile|runtime reference")
DOT_AGENT_ONLY = re.compile(r"verdict\.py|Agents may merge|Any other harness update|ChatGPT|`correct` skill")


def body():
    out, section = [], ""
    for item in re.split(r"\n\s*\n|\n(?=- |#)", (ROOT / "AGENTS.md").read_text()):
        if item.lstrip().startswith("|"):
            if section in KEEP:
                out.append(item.strip())
            continue
        item = " ".join(item.split())
        section = item[3:] if item.startswith("## ") else section
        if section and section not in KEEP:
            continue
        pause = section == "Always pause" and item.startswith("- ")
        drop = DOT_AGENT_ONLY if pause else re.compile(f"{MAC_ONLY.pattern}|{DOT_AGENT_ONLY.pattern}")
        clauses, kept = re.split(r"(?<=[.;])\s+", item), []
        if item.startswith("- ") and drop.search(clauses[0]):
            continue
        for clause in clauses:
            if not drop.search(clause):
                kept.append(clause)
            elif kept:
                kept[-1] = re.sub(r";$", ".", kept[-1])
        item = " ".join(kept)
        if pause and kept:
            item = item[:-1] + clauses[-1][-1]
        out.append(item)
    return "\n\n".join(filter(None, out)) + "\n"


def status(root, wanted):
    if not root.is_dir():
        return "no folder"
    if not (root / RULES).is_file():
        return "missing"
    text = (root / RULES).read_text()
    return "hand-edited" if hand_edited(text) else "current" if text.partition("\n")[2] == wanted else "stale"


def drift(root, wanted):
    agents = root / "AGENTS.md"
    mine = ADOPTED.search(agents.read_text(errors="ignore")) if agents.is_file() else None
    if not mine:
        return None
    latest = ADOPTED.search((ROOT / "template/AGENTS.md").read_text())[1]
    misses = [name for name, ok in checks(root) if not ok]
    opted_out = (root / "template/sync-rules.py").is_file() or not (root / RULES).is_file()
    rules = "current" if opted_out else status(root, wanted)
    gaps = []
    if int(mine[1]) < int(latest):
        gaps.append(f"it follows template {mine[1]}, not {latest}: upgrade it by the template entries in "
                    "~/.dot-agent/RELEASES.md")
    if misses:
        gaps.append(f"conform misses {', '.join(misses)}: `~/.dot-agent/template/apply.sh {root}` adds starter files")
    if rules != "current":
        first = "move its edits into dot-agent's AGENTS.md and delete it, then " if rules == "hand-edited" else ""
        gaps.append(f"its cloud rules file is {rules}: {first}`python3 ~/.dot-agent/template/sync-rules.py write {root}`")
    return gaps


def main(verb="", *repos):
    if verb not in ("write", "check", "drift") or not repos:
        print("usage: sync-rules.py write|check|drift <repo>... [--json]", file=sys.stderr)
        return 2
    wanted, report = body(), []
    for root in (Path(repo).expanduser().resolve() for repo in repos):
        if verb == "drift":
            report.append({"repo": str(root), "gaps": drift(root, wanted)})
            continue
        state = status(root, wanted)
        if verb == "write" and state in ("missing", "stale"):
            (root / RULES).parent.mkdir(parents=True, exist_ok=True)
            stamp = f"{(ROOT / 'VERSION').read_text().strip()} sha256:{hashlib.sha256(wanted.encode()).hexdigest()}"
            (root / RULES).write_text(f"<!-- dot-agent {stamp} generated by template/sync-rules.py from dot-agent's "
                                      f"AGENTS.md; edit there, then rerun write -->\n{wanted}")
            state = "written"
        report.append({"repo": str(root), "status": state})
    print(json.dumps(report, indent=2))
    return int(any(r.get("gaps") or r.get("status") in ("missing", "stale", "hand-edited", "no folder") for r in report))


if __name__ == "__main__":
    sys.exit(main(*[a for a in sys.argv[1:] if a != "--json"]))
