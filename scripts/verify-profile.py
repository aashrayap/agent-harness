#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

sys.dont_write_bytecode = True
from toml_edit import strict_loads

HOME = Path.home()
DOT_AGENT = Path(os.environ.get("DOT_AGENT_HOME", HOME / ".dot-agent"))
STATE = Path(os.environ.get("DOT_AGENT_STATE_HOME", DOT_AGENT / "state"))
CODEX = Path(os.environ.get("CODEX_HOME", HOME / ".codex"))
CLAUDE = Path(os.environ.get("CLAUDE_HOME", HOME / ".claude"))
GENERATED = STATE / "generated" / "AGENTS.md"
GENERATED_REFERENCE = STATE / "generated" / "docs" / "harness-runtime-reference.md"

RUNTIME_HOMES = {"codex": CODEX, "claude": CLAUDE}
AUTOMATION_MODELS = {"gpt-6.1-sol", "gpt-6-astra"}
failures: list[str] = []


def check(ok: bool, label: str, detail: str = "") -> None:
    if ok:
        print(f"  PASS  {label}")
    else:
        line = f"{label}{' — ' + detail if detail else ''}"
        failures.append(line)
        print(f"  FAIL  {line}")


def warn(label: str) -> None:
    print(f"  WARN  {label}")


def automation_model_warnings(codex_home: Path) -> list[str]:
    found = []
    for path in sorted((codex_home / "automations").glob("*/automation.toml")):
        try:
            model = strict_loads(path.read_text(encoding="utf-8")).get("model")
        except (OSError, ValueError) as error:
            found.append(f"automation {path.parent.name}: unreadable ({type(error).__name__})")
            continue
        if model is not None and model not in AUTOMATION_MODELS:
            found.append(f"automation {path.parent.name}: model {model!r} is not "
                         f"{' or '.join(sorted(AUTOMATION_MODELS))}")
    return found


def active_profile() -> str:
    marker = STATE / "machine-profile"
    return marker.read_text().strip() if marker.is_file() else ""


def read_list(profile_dir: Path, name: str) -> set[str]:
    f = profile_dir / name
    if not f.is_file():
        return set()
    return {l.strip() for l in f.read_text().splitlines() if l.strip()}


def source_skills() -> dict[str, Path]:
    out = {}
    for skill_md in sorted((DOT_AGENT / "skills").glob("*/*/SKILL.md")):
        out[skill_md.parent.name] = skill_md.parent
    return out


def skill_entry(skill_dir: Path, runtime: str) -> Path | None:
    for candidate in (skill_dir / runtime / "SKILL.md", skill_dir / "SKILL.md"):
        if candidate.is_file():
            return candidate
    return None


def generated_bytecode(path: Path) -> bool:
    return "__pycache__" in path.parts or path.suffix in (".pyc", ".pyo")


def stale_file(runtime: str, skill_dir: Path, name: str) -> str | None:
    installed = RUNTIME_HOMES[runtime] / "skills" / name
    entry = skill_entry(skill_dir, runtime)
    pairs = [(entry, installed / "SKILL.md")] if entry else []
    if entry and entry.parent != skill_dir:
        pairs += [(f, installed / f.relative_to(entry.parent))
                  for f in entry.parent.rglob("*")
                  if f.is_file() and f != entry and not generated_bytecode(f)]
    for shared in ("scripts", "assets", "references", "shared", "agents", "playbooks", "principles"):
        src = skill_dir / shared
        if src.is_dir():
            pairs += [(f, installed / shared / f.relative_to(src))
                      for f in src.rglob("*")
                      if f.is_file() and not generated_bytecode(f)]
    pairs += [(f, installed / f.name) for f in sorted(skill_dir.glob("*.md")) if f.name != "SKILL.md"]
    for src, dst in pairs:
        if not dst.is_file() or dst.read_bytes() != src.read_bytes():
            return str(src.relative_to(skill_dir))
    expected = {dst.relative_to(installed) for _, dst in pairs}
    actual = {path.relative_to(installed) for path in installed.rglob("*") if path.is_file()}
    generated = sorted(str(path) for path in actual if generated_bytecode(path))
    if generated:
        return f"generated bytecode present: {generated[0]}"
    unexpected = sorted(str(path) for path in actual - expected)
    if unexpected:
        return f"unexpected installed file: {unexpected[0]}"
    return None


def linked_elsewhere(path: Path) -> bool:
    if not path.is_symlink():
        return False
    target = Path(os.path.normpath(path.parent / os.readlink(path)))
    return not target.is_relative_to(DOT_AGENT / "skills")


def installed_skill_names(root: Path) -> set[str]:
    if not root.is_dir():
        return set()
    return {
        path.name for path in root.iterdir()
        if not path.name.startswith(".") and (path.is_dir() or path.is_symlink())
    }


def locked_in(lock, settings):
    if not isinstance(lock, dict):
        return lock == settings
    return isinstance(settings, dict) and all(locked_in(value, settings.get(key)) for key, value in lock.items())


def main() -> int:
    profile = active_profile()
    print(f"verify-profile: profile={profile or '<none>'} runtime={ARGS.runtime}")

    if profile:
        check((DOT_AGENT / "profiles" / profile).is_dir(),
              f"machine profile {profile!r} exists under profiles/")

    hooks_path = subprocess.run(["git", "-C", str(DOT_AGENT), "config", "--get", "core.hooksPath"],
                                capture_output=True, text=True).stdout.strip()
    check(hooks_path == ".githooks", "git core.hooksPath is .githooks (rerun setup.sh)")

    runtimes = {"codex": ["codex"], "all": ["codex", "claude"], "claude": ["claude"]}[ARGS.runtime]
    codex_md = CODEX / "AGENTS.md"
    resolved = codex_md.resolve() if codex_md.is_symlink() else None
    if "codex" in runtimes:
        check(resolved == GENERATED.resolve(), "codex AGENTS.md → generated file",
              f"resolves to {resolved}")
    else:
        check(resolved != GENERATED.resolve(), "codex AGENTS.md retired (Claude-only)",
              "still links to the generated file (rerun setup.sh --runtime claude)")
    expected = (DOT_AGENT / "AGENTS.md").read_bytes()
    fragment = DOT_AGENT / "profiles" / profile / "AGENTS.md" if profile else None
    if fragment and fragment.is_file():
        expected += b"\n" + fragment.read_bytes()
    check(GENERATED.is_file() and GENERATED.read_bytes() == expected,
          "generated file == base + active fragment (rerun setup.sh if stale)")

    effective = GENERATED.read_text() if GENERATED.is_file() else ""
    for profile_dir in sorted((DOT_AGENT / "profiles").iterdir()):
        if not profile_dir.is_dir():
            continue
        for marker in sorted(read_list(profile_dir, "markers")):
            if profile_dir.name == profile:
                check(marker in effective,
                      f"active marker present: {marker!r}")
            else:
                check(marker not in effective,
                      f"foreign profile leak: {profile_dir.name} marker {marker!r} in instructions")

    if "codex" in runtimes:
        config_path = CODEX / "config.toml"
        config = strict_loads(config_path.read_text()) if config_path.is_file() else {}
        check((config.get("model"), config.get("model_reasoning_effort")) == ("gpt-6.1-sol", "high"),
              "codex root model gpt-6.1-sol/high")
        agents = config.get("agents", {})
        check((agents.get("default_subagent_model"), agents.get("default_subagent_reasoning_effort"))
              == ("gpt-6.1-sol", "medium"), "codex subagents gpt-6.1-sol/medium")
        check(config.get("features", {}).get("multi_agent_v2")
              == {"expose_spawn_agent_model_overrides": False},
              "codex hides spawn_agent model overrides")
        for line in automation_model_warnings(CODEX):
            warn(line)

    if "claude" in runtimes:
        settings_path = CLAUDE / "settings.json"
        settings = json.loads(settings_path.read_text()) if settings_path.is_file() else {}
        lock = json.loads((DOT_AGENT / "claude/model-lock.json").read_text())
        check(locked_in(lock, settings),
              "claude settings match claude/model-lock.json (rerun setup.sh)")
        check("**/.claude/rules/dot-agent.md" in (settings.get("claudeMdExcludes") or []),
              "claude settings skip the cloud rules copy, which ~/.claude/CLAUDE.md already loads (rerun setup.sh)")
        wanted = json.loads((DOT_AGENT / "claude/hooks.json").read_text())
        hooks = settings.get("hooks") if isinstance(settings.get("hooks"), dict) else {}
        check(all(isinstance(hooks.get(event), list) and all(group in hooks[event] for group in groups)
                  for event, groups in wanted.items()),
              "claude settings carry the claude/hooks.json hooks (rerun setup.sh)")
        env = settings.get("env") if isinstance(settings.get("env"), dict) else {}
        loaded = {os.path.expanduser(item) for item in str(env.get("CLAUDE_CODE_PLUGIN_DIRS") or "").split(os.pathsep)}
        for mod in sorted((DOT_AGENT / "claude/mods").iterdir()) if (DOT_AGENT / "claude/mods").is_dir() else []:
            check((mod / ".claude-plugin/plugin.json").is_file() and os.path.expanduser(f"~/.dot-agent/claude/mods/{mod.name}") in loaded,
                  f"claude loads the {mod.name} mod: its plugin.json exists and CLAUDE_CODE_PLUGIN_DIRS names it "
                  "(rerun setup.sh)")
        claude_md = CLAUDE / "CLAUDE.md"
        text = claude_md.read_text(errors="replace") if claude_md.is_file() else ""
        first = next(iter(text.splitlines()), "").strip()
        forms = {f"@{GENERATED}"}
        if GENERATED.is_relative_to(HOME):
            forms.add(f"@~/{GENERATED.relative_to(HOME)}")
        check(first in forms, "claude CLAUDE.md starts by importing the generated file "
              "(rerun setup.sh if missing)")
        reference = CLAUDE / "docs" / "harness-runtime-reference.md"
        check(reference.is_file() and not reference.is_symlink() and GENERATED_REFERENCE.is_file()
              and reference.read_bytes() == GENERATED_REFERENCE.read_bytes(),
              "claude runtime reference == generated copy (rerun setup.sh if stale)")
        runner = Path("scheduled-tasks/gardening-hunter/SKILL.md")
        check((CLAUDE / runner).is_file() and (CLAUDE / runner).read_bytes()
              == (DOT_AGENT / "claude" / runner).read_bytes(),
              "claude gardening-hunter runner == claude/scheduled-tasks copy (rerun setup.sh if stale)")

    provided = read_list(DOT_AGENT / "profiles" / profile, "provided-skills") if profile else set()
    sources = source_skills()
    eligible = set(sources) - provided
    for runtime in runtimes:
        actual = installed_skill_names(RUNTIME_HOMES[runtime] / "skills")
        check(eligible <= actual, f"managed skill inventory present ({runtime})",
              f"missing={sorted(eligible - actual)} extra={sorted(actual - eligible)}")
        registry = STATE / f"managed-{runtime}-skills.json"
        managed = set(json.loads(registry.read_text())) if registry.is_file() else set()
        retired = sorted(name for name in (managed - eligible - provided) & actual
                         if not linked_elsewhere(RUNTIME_HOMES[runtime] / "skills" / name))
        check(not retired, f"retired managed skills absent ({runtime})", f"installed={retired}")

    for name, skill_dir in sources.items():
        for runtime in runtimes:
            installed = RUNTIME_HOMES[runtime] / "skills" / name
            if name in provided:
                continue
            check((installed / "SKILL.md").is_file(), f"skill installed ({runtime}): {name}")
            stale = stale_file(runtime, skill_dir, name)
            check(stale is None, f"{runtime} payload fresh: {name}",
                  f"stale/missing: {stale} (rerun setup.sh)")

    print()
    if failures:
        print(f"verify-profile: FAIL ({len(failures)} failure(s))")
        return 1
    print("verify-profile: PASS")
    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--runtime", choices=("codex", "all", "claude"),
                        help="codex, claude, or all for both (default: state/runtime-scope, else codex)")
    ARGS = parser.parse_args()
    if ARGS.runtime is None:
        scope_file = STATE / "runtime-scope"
        scope = scope_file.read_text().strip() if scope_file.is_file() else ""
        if scope and scope not in ("codex", "all", "claude"):
            parser.error(f"{scope_file} must contain codex, all or claude")
        ARGS.runtime = scope or "codex"
    sys.exit(main())
